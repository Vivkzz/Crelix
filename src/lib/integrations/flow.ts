// EKAM AI Flow — deterministic prompt-to-HTML launch page generator.
// No external API or key required. Produces a self-contained, styled HTML page
// the user can preview, download, and deploy.

function titleCase(s: string) {
  return s.replace(/\w\S*/g, (w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
}

function escapeHtml(s: string) {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));
}

function deriveName(prompt: string) {
  const p = prompt.trim();
  const m = p.match(
    /(?:build|create|make|generate|design|launch|a|an|the)?\s*(.+?)(?:\s+(?:for|aimed at|targeting|to help|that helps)\s|$)/i
  );
  const core = (m && m[1] ? m[1] : p).replace(/[.!?]+$/, "").trim();
  const name = titleCase(core).slice(0, 60);
  return name || "Your Product";
}

